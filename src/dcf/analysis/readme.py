"""Results table and chart SVGs for the README, drawn from results/valuations.json.

`python scripts/readme_assets.py` rewrites the table between the README markers and the
SVGs under docs/img/. tests/test_readme.py fails if either is stale.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESULTS = ROOT / "results" / "valuations.json"
README = ROOT / "README.md"
IMG = ROOT / "docs" / "img"
START, END = "<!-- results:start -->", "<!-- results:end -->"

BG, CARD, BORDER, TEXT, MUTED = "#0B0F14", "#111827", "#1F2937", "#E5E7EB", "#9CA3AF"
ACCENT, NEG, WARN, HIST = "#10B981", "#F87171", "#FBBF24", "#4B5563"
FONT = "Inter, system-ui, -apple-system, Segoe UI, sans-serif"
MONO = "JetBrains Mono, ui-monospace, SFMono-Regular, Menlo, monospace"


def load(path: Path = RESULTS) -> dict:
    return json.loads(path.read_text())


def _usd(v: float) -> str:
    return f"${v:,.2f}"


def _pct(v: float, d: int = 1) -> str:
    return f"{v * 100:.{d}f}%"


def results_table(d: dict) -> str:
    rows = [
        "| Ticker | Market price | DCF base | Bear – Bull | Upside (base) | WACC | MC P5 – P95 | P(value > price) | Implied 10y growth |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for t, a in d["tickers"].items():
        b, sc, mc, rv = a["base"], a["scenarios"], a["monte_carlo"], a["reverse_dcf"]
        p = mc["percentiles"]
        ig = rv.get("implied_growth")
        rows.append(
            f"| {t} | {_usd(b['market_price'])} | {_usd(b['implied_price'])} "
            f"| {_usd(sc['bear']['implied_price'])} – {_usd(sc['bull']['implied_price'])} "
            f"| {b['upside'] * 100:+.0f}% | {_pct(b['wacc'], 2)} "
            f"| {_usd(p['p5'])} – {_usd(p['p95'])} | {_pct(mc['prob_value_gt_price'])} "
            f"| {_pct(ig) if ig is not None else 'n/a'} |"
        )
    rates = d["rates"]
    rows.append("")
    rows.append(
        f"Snapshot {d['snapshot_date']} · rf {_pct(rates['rf'], 2)} (FRED DGS10, {rates['rf_date']}) · "
        f"ERP {_pct(rates['erp']['value'], 2)} (Damodaran, {rates['erp']['as_of']}) · "
        f"Monte Carlo {next(iter(d['tickers'].values()))['monte_carlo']['n_draws']:,} draws · "
        f"schema {d['schema_version']}. Generated by `scripts/readme_assets.py`."
    )
    return "\n".join(rows)


def render_readme(readme: str, d: dict) -> str:
    i, j = readme.index(START) + len(START), readme.index(END)
    return readme[:i] + "\n" + results_table(d) + "\n" + readme[j:]


def _svg(w: int, h: int, body: str, title: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" '
        f'aria-label="{title}"><title>{title}</title>'
        f'<rect width="{w}" height="{h}" rx="12" fill="{CARD}" stroke="{BORDER}"/>{body}</svg>\n'
    )


def _text(x, y, s, size=12, fill=TEXT, anchor="start", font=FONT, weight=400) -> str:
    return (
        f'<text x="{x:.1f}" y="{y:.1f}" font-family="{font}" font-size="{size}" fill="{fill}" '
        f'text-anchor="{anchor}" font-weight="{weight}">{s}</text>'
    )


def value_vs_price_svg(d: dict) -> str:
    """Bear–bull range, base point and market price per ticker, as a ratio of market price."""
    w, h, lw, top, row = 760, 70 + 52 * len(d["tickers"]), 70, 64, 52
    iw = w - lw - 210  # right column holds the $ labels
    lo, hi = 0.0, 3.0
    x = lambda r: lw + (min(max(r, lo), hi) - lo) / (hi - lo) * iw  # noqa: E731
    out = [_text(24, 32, "DCF value vs market price (bear – bull range, ● base)", 15, weight=600)]
    for r in (0, 0.5, 1, 1.5, 2, 2.5, 3):
        out.append(
            f'<line x1="{x(r):.1f}" x2="{x(r):.1f}" y1="{top - 8}" y2="{h - 24}" stroke="{BORDER}"/>'
        )
        out.append(_text(x(r), h - 8, f"{r:g}×", 11, MUTED, "middle", MONO))
    out.append(
        f'<line x1="{x(1):.1f}" x2="{x(1):.1f}" y1="{top - 8}" y2="{h - 24}" stroke="{WARN}" stroke-width="2"/>'
    )
    out.append(_text(x(1) + 4, top - 12, "market price", 11, WARN, font=MONO))
    for i, (t, a) in enumerate(d["tickers"].items()):
        m = a["base"]["market_price"]
        bear, base, bull = (
            a["scenarios"][k]["implied_price"] / m for k in ("bear", "base", "bull")
        )
        y = top + i * row + row / 2
        col = ACCENT if base >= 1 else NEG
        out.append(_text(lw - 12, y + 4, t, 13, TEXT, "end", MONO, 600))
        out.append(
            f'<rect x="{x(bear):.1f}" y="{y - 9:.1f}" width="{x(bull) - x(bear):.1f}" height="18" rx="4" fill="{col}" opacity="0.35"/>'
        )
        out.append(f'<circle cx="{x(base):.1f}" cy="{y:.1f}" r="6" fill="{col}"/>')
        out.append(
            _text(
                w - 24,
                y + 4,
                f"{_usd(a['base']['implied_price'])} vs {_usd(m)}",
                11,
                MUTED,
                "end",
                MONO,
            )
        )
    return _svg(w, h, "".join(out), "DCF value versus market price for six companies")


def histogram_svg(d: dict, ticker: str = "AAPL") -> str:
    a = d["tickers"][ticker]
    mc, m = a["monte_carlo"], a["base"]["market_price"]
    edges, counts = mc["histogram"]["edges"], mc["histogram"]["counts"]
    w, h, l, r, t, b = 760, 336, 24, 24, 80, 40
    lo, hi = min(edges[0], m), max(edges[-1], m)
    x = lambda v: l + (v - lo) / (hi - lo) * (w - l - r)  # noqa: E731
    cmax = max(counts)
    y = lambda c: h - b - c / cmax * (h - t - b)  # noqa: E731
    out = [
        _text(
            24,
            32,
            f"{ticker} Monte Carlo: {mc['n_draws']:,} draws of value per share",
            15,
            weight=600,
        )
    ]
    for i, c in enumerate(counts):
        x0, x1 = x(edges[i]), x(edges[i + 1])
        out.append(
            f'<rect x="{x0 + 0.5:.1f}" y="{y(c):.1f}" width="{max(x1 - x0 - 1, 1):.1f}" height="{h - b - y(c):.1f}" fill="{ACCENT}"/>'
        )
    out.append(f'<line x1="{l}" x2="{w - r}" y1="{h - b}" y2="{h - b}" stroke="{BORDER}"/>')
    p = mc["percentiles"]
    for n, (k, v, col) in enumerate(
        (
            ("P5", p["p5"], MUTED),
            ("P50", p["p50"], TEXT),
            ("P95", p["p95"], MUTED),
            ("Market", m, WARN),
        )
    ):
        dash = "" if k == "Market" else ' stroke-dasharray="4 3"'
        out.append(
            f'<line x1="{x(v):.1f}" x2="{x(v):.1f}" y1="{t - 6}" y2="{h - b}" stroke="{col}" stroke-width="{2 if k == "Market" else 1.25}"{dash}/>'
        )
        anchor = "end" if x(v) > w - 90 else "start" if x(v) < 90 else "middle"
        out.append(_text(x(v), t - 12 - (n % 2) * 14, f"{k} {_usd(v)}", 11, col, anchor, MONO))
    for v in (lo, (lo + hi) / 2, hi):
        anchor = "start" if v == lo else "end" if v == hi else "middle"
        out.append(_text(x(v), h - b + 18, f"${v:,.0f}", 11, MUTED, anchor, MONO))
    return _svg(w, h, "".join(out), f"{ticker} Monte Carlo distribution of value per share")


def heatmap_svg(d: dict, ticker: str = "AAPL") -> str:
    a = d["tickers"][ticker]
    s, m = a["sensitivity"], a["base"]["market_price"]
    waccs, gs, price = s["wacc"], s["g"], s["price"]
    w, l, t, cw, chh = 760, 84, 64, (760 - 84 - 24) / len(gs), 44
    h = t + chh * len(waccs) + 56

    def col(v):
        r = max(0.5, min(1.5, v / m))
        a_, b_ = (
            ((NEG, "#1F2937"), (r - 0.5) / 0.5) if r < 1 else (("#1F2937", ACCENT), (r - 1) / 0.5)
        )
        c1, c2 = (
            (int(a_[0][i : i + 2], 16) for i in (1, 3, 5)),
            (int(a_[1][i : i + 2], 16) for i in (1, 3, 5)),
        )
        return "#" + "".join(f"{round(p + (q - p) * b_):02X}" for p, q in zip(c1, c2, strict=True))

    out = [
        _text(
            24,
            32,
            f"{ticker} implied price: WACC × terminal growth (market {_usd(m)})",
            15,
            weight=600,
        )
    ]
    for i, wv in enumerate(waccs):
        out.append(_text(l - 10, t + i * chh + chh / 2 + 4, _pct(wv, 1), 11, MUTED, "end", MONO))
        for j in range(len(gs)):
            v = price[i][j]
            xx, yy = l + j * cw, t + i * chh
            if v is None:
                out.append(
                    f'<rect x="{xx + 1:.1f}" y="{yy + 1}" width="{cw - 2:.1f}" height="{chh - 2}" rx="4" fill="{BG}" stroke="{BORDER}"/>'
                )
                continue
            out.append(
                f'<rect x="{xx + 1:.1f}" y="{yy + 1}" width="{cw - 2:.1f}" height="{chh - 2}" rx="4" fill="{col(v)}"/>'
            )
            out.append(_text(xx + cw / 2, yy + chh / 2 + 4, f"{v:,.0f}", 11, TEXT, "middle", MONO))
    for j, gv in enumerate(gs):
        out.append(
            _text(
                l + j * cw + cw / 2,
                t + chh * len(waccs) + 18,
                _pct(gv, 1),
                11,
                MUTED,
                "middle",
                MONO,
            )
        )
    out.append(_text(l + (w - l - 24) / 2, h - 12, "terminal growth g →", 11, MUTED, "middle"))
    return _svg(
        w,
        int(h),
        "".join(out),
        f"{ticker} sensitivity of implied price to WACC and terminal growth",
    )


def assets(d: dict) -> dict[str, str]:
    return {
        "value-vs-price.svg": value_vs_price_svg(d),
        "aapl-monte-carlo.svg": histogram_svg(d, "AAPL"),
        "aapl-sensitivity.svg": heatmap_svg(d, "AAPL"),
    }
